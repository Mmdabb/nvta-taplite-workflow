def _normalize_vdf_dict(vdf_dict: dict) -> dict:
    return {str(key): value for key, value in vdf_dict.items()}


BPR_VDF_DICT = _normalize_vdf_dict(BPR_VDF_DICT)


def _normalize_vdf_code(value: object) -> str:
    text = str(value).strip()
    if text.casefold() == "all":
        return "all"
    try:
        numeric = float(text)
    except ValueError:
        return text
    return str(int(numeric)) if numeric.is_integer() else text


def load_qvdf_vdf_dict(csv_path: str | Path = QVDF_RESOURCE_PATH) -> dict[str, dict]:
    """Load the authoritative link-type QVDF table from ``link_qvdf.csv``.

    Each ``vdf_code`` becomes a lookup key. The required ``all`` row is kept
    under that literal key and is selected only when a link type has no exact
    row. Empty QVDF parameter cells are rejected later for the requested
    assignment period, where the error can name the exact link and field.
    """

    path = Path(csv_path)
    if not path.is_file():
        raise FileNotFoundError(f"QVDF resource CSV is missing: {path}")

    records: dict[str, dict] = {}
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if not reader.fieldnames or "vdf_code" not in reader.fieldnames:
            raise ValueError(f"QVDF resource CSV has no vdf_code column: {path}")

        for line_number, row in enumerate(reader, start=2):
            if str(row.get("data_type", "")).strip().casefold() != "vdf_code":
                raise ValueError(
                    f"Unsupported data_type on line {line_number} of {path}: "
                    f"{row.get('data_type')!r}"
                )
            key = _normalize_vdf_code(row.get("vdf_code", ""))
            if not key:
                raise ValueError(f"Blank vdf_code on line {line_number} of {path}")
            if key in records:
                raise ValueError(f"Duplicate vdf_code {key!r} in {path}")

            record: dict[str, object] = {}
            for field, raw_value in row.items():
                value = "" if raw_value is None else str(raw_value).strip()
                if not value:
                    continue
                if field.startswith("QVDF_"):
                    try:
                        record[field] = float(value)
                    except ValueError as exc:
                        raise ValueError(
                            f"Non-numeric {field}={value!r} on line "
                            f"{line_number} of {path}"
                        ) from exc
                else:
                    record[field] = value
            records[key] = record

    if "all" not in records:
        raise ValueError(
            f"QVDF resource CSV requires a vdf_code='all' fallback row: {path}"
        )

    # NT has no observed calibration table. Preserve the hard-coded baseline
    # parameters for period 4 and use the neutral no-observation PLF.
    for key, record in records.items():
        baseline = QVDF_VDF_DICT.get(key)
        if baseline is None:
            raise ValueError(f"No built-in NT QVDF defaults for vdf_code={key!r}")
        for field in NT_QVDF_PARAMETER_FIELDS:
            value = baseline.get(field)
            if value is None or str(value).strip() == "":
                raise ValueError(
                    f"Built-in NT QVDF default {field!r} is missing for "
                    f"vdf_code={key!r}"
                )
            record[field] = float(value)
        record["QVDF_plf4"] = NT_QVDF_DEFAULT_PLF
    return records


def get_vdf_dict(vdf_type: str = "bpr") -> dict:
    """Return the selected VDF parameter dictionary."""
    normalized = vdf_type.lower()
    if normalized == "bpr":
        return BPR_VDF_DICT
    if normalized == "qvdf":
        return load_qvdf_vdf_dict()
    raise ValueError("vdf_type must be either 'bpr' or 'qvdf'")
